package dev.agenttranslator;

import java.io.File;

/**
 * Офлайн-распознавание текста на снимке: вывеска, меню, скрин переписки.
 *
 * Зачем своё, если бесплатная модель OpenRouter картинки принимает (на устройстве их 10 из 19):
 * вывеска на улице — ровно то место, где сети нет, а скрин чужой переписки не должен уходить
 * третьей стороне. Облако остаётся запасным путём по кнопке, офлайн — основным.
 *
 * Модели ещё не подключены: {@link #ready} — false, и {@link TranslatorService#photoText}
 * уходит в облако. Заглушка отдельным классом, а не «потом допишем в сервисе», чтобы место
 * подключения было названо и его нельзя было потерять.
 *
 * План подключения (ONNX Runtime уже в сборке, NDK не нужен):
 *   models/ocr/det.onnx  — детектор строк (DB), выход — карта вероятностей;
 *   models/ocr/rec.onnx  — распознаватель строки (CTC), латиница с диакритикой pt-BR;
 *   models/ocr/keys.txt  — алфавит распознавателя.
 * Порядок: снимок → уменьшение до 960 px → детектор → рамки строк → вырез и выравнивание →
 * распознаватель → строки сверху вниз. Ни одного числа отсюда в документы не переносить,
 * пока не измерено на телефоне.
 */
public class Ocr {
  public final boolean ready;
  final File dir;

  public Ocr(File modelsDir) {
    dir = new File(modelsDir, "ocr");
    ready = new File(dir, "det.onnx").exists() && new File(dir, "rec.onnx").exists();
  }

  /** Текст со снимка или null, если распознать нечем. */
  public String read(byte[] jpeg) {
    if (!ready) return null;
    return null;
  }
}
